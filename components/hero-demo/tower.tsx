function getIntersectionProxyGeometry(source: THREE.BufferGeometry) {
  const cached = intersectionProxyCache.get(source);
  if (cached) return cached;

  const position = source.getAttribute("position");
  const sourceIndex = source.getIndex();
  const triangleCount = (sourceIndex?.count ?? position.count) / 3;
  const filtered: number[] = [];

  for (let triangle = 0; triangle < triangleCount; triangle += 1) {
    const offset = triangle * 3;
    const a = sourceIndex ? sourceIndex.getX(offset) : offset;
    const b = sourceIndex ? sourceIndex.getX(offset + 1) : offset + 1;
    const c = sourceIndex ? sourceIndex.getX(offset + 2) : offset + 2;

    if (
      Math.max(position.getY(a), position.getY(b), position.getY(c)) >=
      INTERSECTION_PROXY_MIN_Y
    ) {
      filtered.push(a, b, c);
    }
  }

  const proxy = new THREE.BufferGeometry();
  proxy.setAttribute("position", position);
  // All three source meshes fit 16-bit indices; let three choose Uint16 here
  // instead of forcing twice the index bandwidth with Uint32.
  proxy.setIndex(filtered);
  // The shared attribute still contains every source vertex, so borrowing the
  // source bounds is both conservative and avoids another full-buffer scan.
  if (!source.boundingBox) source.computeBoundingBox();
  if (!source.boundingSphere) source.computeBoundingSphere();
  proxy.boundingBox = source.boundingBox?.clone() ?? null;
  proxy.boundingSphere = source.boundingSphere?.clone() ?? null;
  intersectionProxyCache.set(source, proxy);
  return proxy;
}

export type TowerMode = "glow" | "metal" | "sparkle";

/**
 * The sparkle: the real tower's 20,000 bulbs going off for five minutes on
 * the hour, compressed into a permanent state.
 *
 * All in the fragment shader, driven by `TSL.time`: local space is diced
 * into cells, each cell gets a stable hash, and each hash phase-offsets a
 * shared slow cycle so a cell pops for a few tens of ms and stays dark for
 * the rest of it. The pops write to `emissiveNode`, which the pipeline's
 * emissive MRT attachment feeds straight into bloom — that's the glitter.
 * The base material is the dark iron the tower actually is at dusk.
 */
function makeSparkleNodes() {
  const cell = TSL.floor(TSL.positionLocal.mul(0.9));
  const seed = TSL.fract(
    TSL.sin(cell.dot(TSL.vec3(127.1, 311.7, 74.7))).mul(43758.5453),
  );
  // Every cell runs the same 2.5s cycle at a private phase; the step keeps
  // ~1.5% of it lit, so at any instant a sparse random scatter is popping.
  const cycle = TSL.fract(TSL.time.mul(0.4).add(seed));
  const flash = TSL.step(0.985, cycle);
  const brightness = seed.mul(0.6).add(0.4);

  return {
    emissiveNode: TSL.color("#fff3d0").mul(flash.mul(brightness).mul(8)),
  };
}

/**
 * The summit beacon: two opposed fake-volumetric beams, shaded the way
 * drei's `<SpotLight volumetric>` (pmndrs volumetric-spotlight example)
 * does its cone — a TSL port of that GLSL SpotLightMaterial, which can't
 * run on WebGPU directly. Two terms multiply:
 *
 * 1. Linear distance attenuation from the hub along the beam.
 * 2. `anglePower` falloff on the view-space normal: silhouette-edge
 *    fragments (normal ⟂ view) fade out, the tube's core (normal toward
 *    camera) stays bright. This is what turns a hard-edged cone into a
 *    soft light shaft with a luminous core.
 *
 * The example's third trick — depth-buffer soft intersection — is skipped:
 * these beams live in the sky and rarely cross geometry. Additive, no
 * depth write, double-sided (abs() covers the flipped back-face normals).
 */
function makeBeamNodes() {
  // Geometry below is translated so the hub is at y = 0, beam along +y.
  const along = TSL.positionLocal.y.div(BEAM_LENGTH).clamp(0.0, 1.0);
  const distanceFade = TSL.oneMinus(along);
  const angleFade = TSL.pow(TSL.abs(TSL.normalView.z), 4.0);
  return { opacityNode: distanceFade.mul(angleFade).mul(0.6) };
}

/** Beam length/flare in the tower's local (pre-scale-0.2) units. */
const BEAM_LENGTH = 600;
const BEAM_FLARE = 36;

function Beacon({ speed = 0.6 }: { speed?: number }) {
  const spinRef = useRef<THREE.Group>(null);

  const geometry = useMemo(() => {
    // High radial segmentation on purpose: the anglePower falloff shades by
    // interpolated silhouette normals, and a coarse tube shows facets.
    const g = new THREE.CylinderGeometry(
      BEAM_FLARE,
      1.5,
      BEAM_LENGTH,
      64,
      8,
      true,
    );
    // Hub end at the origin, beam extending along +y (then rotated flat).
    g.translate(0, BEAM_LENGTH / 2, 0);
    return g;
  }, []);

  // Module-level creator, so the memo inside `useLocalNodes` holds until the
  // shared TSL stores (or HMR) invalidate it. Both beams share the graph.
  const beam = useLocalNodes(makeBeamNodes);

  useFrame((_, delta) => {
    if (spinRef.current) spinRef.current.rotation.y += delta * speed;
  });

  return (
    <group ref={spinRef}>
      {[-Math.PI / 2, Math.PI / 2].map((roll) => (
        <mesh key={roll} geometry={geometry} rotation-z={roll}>
          <meshBasicNodeMaterial
            color="#ffeec2"
            transparent
            blending={THREE.AdditiveBlending}
            side={THREE.DoubleSide}
            depthWrite={false}
            opacityNode={beam.opacityNode}
          />
        </mesh>
      ))}
    </group>
  );
}

